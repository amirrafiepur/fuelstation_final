#: Highest resolution pages are rendered at before being sent to the
#: printer. 300 dpi is sharp for text/tables and keeps one A4 page around
#: 9 megapixels in memory.
PRINT_DPI_CAP = 300

#: Lower-cased fragments that identify software "printers" that save or
#: send a document somewhere instead of putting it on paper.
VIRTUAL_PRINTER_MARKERS = (
    "pdf",
    "xps",
    "onenote",
    "fax",
    "document writer",
    "image writer",
    "snagit",
    "print to file",
    "send to",
    "virtual",
)


class PrintError(RuntimeError):
    """The document could not be sent to the printer."""


# ---------------------------------------------------------------------------
# Printer detection
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class PrinterCandidate:
    name: str
    is_default: bool = False
    has_error: bool = False


@dataclass(frozen=True)
class PrintOutcome:
    """What happened to a generated PDF. `status` is one of
    "printed", "no_printer", "failed"."""

    status: str
    printer_name: Optional[str] = None
    detail: str = ""


def is_virtual_printer(name: str) -> bool:
    lowered = (name or "").lower()
    return any(marker in lowered for marker in VIRTUAL_PRINTER_MARKERS)


def choose_printer(candidates: Iterable[PrinterCandidate]) -> Optional[PrinterCandidate]:
    """
    Pick the printer to use: the system default if it is a real, healthy
    printer, otherwise the first real, healthy one. Returns None when
    there is no usable physical printer.
    """
    usable = [
        c for c in candidates
        if c.name and not c.has_error and not is_virtual_printer(c.name)
    ]
    for candidate in usable:
        if candidate.is_default:
            return candidate
    return usable[0] if usable else None


def list_printers() -> list[PrinterCandidate]:
    """Printers the OS reports (requires a running QApplication)."""
    from PySide6.QtPrintSupport import QPrinter, QPrinterInfo

    default_name = QPrinterInfo.defaultPrinterName()
    candidates = []
    for info in QPrinterInfo.availablePrinters():
        candidates.append(
            PrinterCandidate(
                name=info.printerName(),
                is_default=bool(info.isDefault()) or info.printerName() == default_name,
                has_error=info.state() == QPrinter.PrinterState.Error,
            )
        )
    return candidates


def find_printer() -> Optional[PrinterCandidate]:
    return choose_printer(list_printers())


# ---------------------------------------------------------------------------
# Sending a PDF to a printer
# ---------------------------------------------------------------------------


def _printer_for(name: str):
    """A QPrinter bound to the named OS printer."""
    from PySide6.QtPrintSupport import QPrinter, QPrinterInfo

    for info in QPrinterInfo.availablePrinters():
        if info.printerName() == name:
            return QPrinter(info, QPrinter.PrinterMode.HighResolution)
    raise PrintError(f"Printer {name!r} is no longer available.")


def print_pdf(
    pdf_path,
    printer_name: str,
    *,
    printer_factory: Optional[Callable[[str], object]] = None,
    max_dpi: int = PRINT_DPI_CAP,
) -> int:
    """
    Render every page of `pdf_path` with QtPdf and print it on the named
    printer, silently. Returns the number of pages sent. Raises
    PrintError on any failure.

    `printer_factory(name)` may return any QPrinter (tests use one that
    writes a PDF file instead of using paper); by default the real OS
    printer is used. The sheet is A4 -- orientation follows the PDF (wide
    reports are landscape) -- and drawn full-bleed, because the PDF
    already carries its own 8 mm margins.
    """
    from PySide6.QtCore import QRectF, QSize
    from PySide6.QtGui import QColor, QImage, QPageLayout, QPageSize, QPainter
    from PySide6.QtPdf import QPdfDocument
    from PySide6.QtPrintSupport import QPrinter

    path = Path(pdf_path)
    if not path.is_file():
        raise PrintError(f"PDF not found: {path}")

    document = QPdfDocument()
    load_error = document.load(str(path))
    if load_error != QPdfDocument.Error.None_:
        raise PrintError(f"PDF could not be read ({load_error.name}).")
    page_count = document.pageCount()
    if page_count < 1:
        raise PrintError("PDF has no pages.")

    printer = (printer_factory or _printer_for)(printer_name)
    if not printer.isValid():
        raise PrintError(f"Printer {printer_name!r} is not valid.")

    first_page = document.pagePointSize(0)
    printer.setPageSize(QPageSize(QPageSize.PageSizeId.A4))
    printer.setPageOrientation(
        QPageLayout.Orientation.Landscape
        if first_page.width() > first_page.height()
        else QPageLayout.Orientation.Portrait
    )
    printer.setFullPage(True)
    printer.setCopyCount(1)

    dpi = max(72, min(int(printer.resolution() or max_dpi), max_dpi))

    painter = QPainter()
    if not painter.begin(printer):
        raise PrintError("The printer could not be opened for printing.")

    try:
        target = QRectF(printer.pageRect(QPrinter.Unit.DevicePixel))
        for index in range(page_count):
            if index:
                if not printer.newPage():
                    raise PrintError(f"The printer rejected page {index + 1}.")
            size = document.pagePointSize(index)
            pixel_size = QSize(
                max(1, round(size.width() / 72.0 * dpi)),
                max(1, round(size.height() / 72.0 * dpi)),
            )
            rendered = document.render(index, pixel_size)
            if rendered.isNull():
                raise PrintError(f"Page {index + 1} could not be rendered.")
            # Composite on opaque white so transparent areas never print black.
            canvas = QImage(pixel_size, QImage.Format.Format_RGB32)
            canvas.fill(QColor("white"))
            canvas_painter = QPainter(canvas)
            canvas_painter.drawImage(0, 0, rendered)
            canvas_painter.end()
            painter.drawImage(target, canvas)
    finally:
        painter.end()

    return page_count


# ---------------------------------------------------------------------------
# Orchestration: print, or fall back to showing the PDF
# ---------------------------------------------------------------------------


def print_or_fallback(
    pdf_path,
    *,
    open_in_viewer: Callable[[Path], bool],
    show_message: Callable[[str, str, str], None],
    show_status: Optional[Callable[[str], None]] = None,
    find_printer_fn: Callable[[], Optional[PrinterCandidate]] = find_printer,
    send_to_printer: Callable[[Path, str], object] = print_pdf,
) -> PrintOutcome:
    """
    Print `pdf_path` directly if a printer is available; otherwise (or if
    printing fails) tell the operator in Persian and open the PDF.

    `show_message(title, text, level)` shows a blocking message
    (level "info" or "warning"); `show_status(text)` shows a short
    non-blocking confirmation; `open_in_viewer(path)` returns whether the
    OS viewer was launched. Nothing here raises: every failure ends in one
    of the three PrintOutcome statuses with the document still reachable.
    """
    path = Path(pdf_path)

    def fall_back_to_viewer() -> None:
        opened = False
        try:
            opened = bool(open_in_viewer(path))
        except Exception:  # pragma: no cover - defensive, OS specific
            logger.exception("Could not open %s in the PDF viewer", path)
        if not opened:
            show_message(
                MSG_VIEWER_FAILED_TITLE, MSG_VIEWER_FAILED.format(path=path), "warning"
            )

    try:
        printer = find_printer_fn()
    except Exception:
        logger.exception("Printer detection failed; treating as no printer")
        printer = None

    if printer is None:
        show_message(MSG_NO_PRINTER_TITLE, MSG_NO_PRINTER, "info")
        fall_back_to_viewer()
        return PrintOutcome("no_printer")

    try:
        send_to_printer(path, printer.name)
    except Exception as exc:
        logger.exception("Printing %s on %r failed", path, printer.name)
        show_message(MSG_PRINT_FAILED_TITLE, MSG_PRINT_FAILED, "warning")
        fall_back_to_viewer()
        return PrintOutcome("failed", printer.name, str(exc))

    if show_status is not None:
        show_status(MSG_PRINTED.format(name=printer.name))
    return PrintOutcome("printed", printer.name)
