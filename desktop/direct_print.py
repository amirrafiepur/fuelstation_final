"""
Direct printing of the application's generated PDFs (Task 2B).

Every print/چاپ button in the app leads to a PDF generated by WeasyPrint
(apps/printing). In the packaged desktop window those PDFs arrive through
QWebEngineProfile.downloadRequested (see desktop/main.py). This module
decides what happens next:

  * A real printer is available  -> the saved PDF is rendered with Qt's
    own PDF engine (QtPdf) and sent straight to that printer. No PDF
    viewer, no print dialog, no confirmation, no second click.
  * No printer is available      -> a clear Persian message is shown and
    the PDF is opened in the OS PDF viewer (the previous behaviour), so
    the operator still gets the document.
  * Printing fails part-way      -> a Persian error is shown and the PDF
    is opened in the viewer as well. The document is never silently lost.

Design notes
------------
* The decision logic (print_or_fallback) takes every side effect as an
  argument, so it is unit-tested without Qt, a printer, or a display.
* Qt is imported lazily inside the functions that need it, so this module
  imports cleanly in the Django test run and in server mode.
* "Printer available" deliberately ignores virtual/software printers
  (Microsoft Print to PDF, XPS Document Writer, OneNote, fax, ...). Sending
  a report to one of those would pop up a "save as" dialog instead of
  printing, which is exactly what this feature must not do.
* Rendering is done page-by-page at <= PRINT_DPI_CAP dpi and drawn onto
  the printer's QPainter, which keeps memory low on the target PC
  (4 GB RAM) while staying sharp for text and table lines.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Iterable, Optional

logger = logging.getLogger("fuelstation")

# ---------------------------------------------------------------------------
# Persian user-facing messages
# ---------------------------------------------------------------------------

